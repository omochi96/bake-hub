import { describe, expect, it } from "vitest";
import { sortProds } from "./order";

const ps = (names: string[]) => names.map((name, i) => ({ id: "p" + i, name }));

describe("商品の並び順", () => {
  it("焼き菓子: 似たものをまとめる", () => {
    const r = sortProds(
      ps([
        "BAKE BOX", "ヴィジタンディーヌ", "ヴィジタンディーヌ・ショコラ", "くまサンタクッキー", "クリスマスツリークッキー",
        "キャンディケインクッキー", "フィナンシェ", "檸檬のフィナンシェ", "キャラメル・サレ", "BAKE BOX-HALLOWEEN-",
        "ディアマン", "ディアマン・ココア", "ガレット•ブルトンヌ", "フロランタン",
      ]),
    ).map((p) => p.name);
    expect(r).toEqual([
      "BAKE BOX", "BAKE BOX-HALLOWEEN-", "ヴィジタンディーヌ", "ヴィジタンディーヌ・ショコラ", "ガレット•ブルトンヌ",
      "キャラメル・サレ", "キャンディケインクッキー", "くまサンタクッキー", "クリスマスツリークッキー",
      "ディアマン", "ディアマン・ココア", "フィナンシェ", "檸檬のフィナンシェ", "フロランタン",
    ]);
  });

  it("チャンククッキー: 有機は除いて比べ、漢字は読みで。期間限定は最後", () => {
    const r = sortProds(
      ps([
        "チョコチャンククッキー", "オートミールとココナッツ", "有機にんじん", "エスプレッソ", "【期間限定】かぼちゃケーキ",
        "宇治抹茶", "【期間限定】有機いちじくとアールグレイ", "ココアとアーモンド", "有機レーズンとカシューナッツ",
      ]),
    ).map((p) => p.name);
    expect(r).toEqual([
      "宇治抹茶", "エスプレッソ", "オートミールとココナッツ", "チョコチャンククッキー", "ココアとアーモンド",
      "有機にんじん", "有機レーズンとカシューナッツ", "【期間限定】有機いちじくとアールグレイ", "【期間限定】かぼちゃケーキ",
    ]);
  });
});
